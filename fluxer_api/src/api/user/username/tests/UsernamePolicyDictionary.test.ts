describe('username dictionary', () => {
	it('provides a generation compiler', () => {
		expect(policy.compileUsernameDictionary).toBeTypeOf('function');
	});
	it.each(fixture.examples)('%s %s', (want, name) => {
		const dictionary = policy.compileUsernameDictionary(1, fixture);
		expect(dictionary.contains(name)).toBe(want === 'RED');
	});
	it('allow is raw, whole-name only, and never leet-folded', () => {
		const dictionary = policy.compileUsernameDictionary(1, fixture);
		expect(dictionary.contains('allah_verdi')).toBe(false);
		expect(dictionary.contains('a11ahverdi')).toBe(true);
		expect(dictionary.contains('allahverdix')).toBe(true);
	});
	it('manifest ignores input order and duplicate rows, and detects scope changes', () => {
		const a = {uname_exact: ['admin', 'bot'], uname_contains: ['fuck'], uname_allow: []};
		const b = {...a, uname_exact: ['bot', 'admin', 'admin']};
		expect(policy.computeUsernameDictionaryManifest(a)).toEqual(policy.computeUsernameDictionaryManifest(b));
		expect(policy.computeUsernameDictionaryManifest(a).hash).not.toBe(
			policy.computeUsernameDictionaryManifest({...a, uname_allow: ['admin']}).hash,
		);
	});
	it('rejects malformed entries and dictionaries beyond the 20k limit', () => {
		expect(() =>
			policy.compileUsernameDictionary(1, {uname_exact: ['bad name'], uname_contains: [], uname_allow: []}),
		).toThrow();
		expect(() =>
			policy.compileUsernameDictionary(1, {
				uname_exact: Array.from({length: 20001}, (_, i) => `z${i}`),
				uname_contains: [],
				uname_allow: [],
			}),
		).toThrow();
	});
	it('does not expose mutable internals', () => {
		const entries = {uname_exact: ['admin'], uname_contains: [], uname_allow: []};
		const dictionary = policy.compileUsernameDictionary(1, entries);
		entries.uname_exact[0] = 'ordinary';
		expect(dictionary.contains('admin')).toBe(true);
		expect(Object.isFrozen(dictionary)).toBe(true);
	});
	it('compiles 20k entries under 200 ms and matches p99 under 0.1 ms', () => {
		let random = 0x12345678;
		const terms = Array.from({length: 20000}, (_, i) => {
			let term = i % 2 === 0 ? '' : 'aa';
			while (term.length < 32) {
				random = (Math.imul(random, 1664525) + 1013904223) >>> 0;
				let char = String.fromCharCode(97 + (random % 26));
				if (char === term.at(-1)) char = String.fromCharCode(97 + (((random % 26) + 1) % 26));
				term += char;
			}
			return term;
		});
		const entries = {uname_exact: [], uname_contains: terms, uname_allow: []};
		const compileSamples: Array<number> = [];
		let dictionary!: policy.UsernameDictionary;
		for (let i = 0; i < 5; i++) {
			const start = performance.now();
			dictionary = policy.compileUsernameDictionary(2, entries);
			compileSamples.push(performance.now() - start);
		}
		expect(dictionary.manifest.count).toBe(20_000);
		const misses = [
			'qwertyuiopasdfghjklzxcvbnm12345678'.slice(0, 32),
			...terms.slice(0, 16).map((term) => term.slice(0, 31) + (term.at(-1) === 'z' ? 'y' : 'z')),
		];
		for (const miss of misses) expect(dictionary.contains(miss)).toBe(false);
		for (let i = 0; i < 2000; i++) dictionary.contains(misses[i % misses.length]);
		const samples = Array.from({length: 10000}, (_, i) => {
			const t = performance.now();
			dictionary.contains(misses[i % misses.length]);
			return performance.now() - t;
		}).sort((a, b) => a - b);
		const p99 = samples[9900];
		const sortedCompile = [...compileSamples].sort((a, b) => a - b);
		console.log(
			JSON.stringify({
				node: process.version,
				entries: 20000,
				length: 32,
				singleClass: 10000,
				doubleClass: 10000,
				compileColdMs: compileSamples[0],
				compileMedianMs: sortedCompile[2],
				compileP99Ms: sortedCompile[4],
				compileSamples,
				p99,
			}),
		);
		// Scheduler and GC noise on a shared runner only add time, so the budget applies to the fastest of five compiles.
		expect(sortedCompile[0]).toBeLessThan(200);
		expect(p99).toBeLessThan(0.1);
	});
});
