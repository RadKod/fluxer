"""Builds the name style fonts listed in packages/fonts/name-styles.json.

Each font comes from google/fonts at the pinned commit, is checked against the lock file, pinned to one instance,
subset to Latin + Latin Extended-A, renamed (OFL Reserved Font Name clause) and written as one WOFF2 file with its own
stylesheet. A font that does not cover Turkish fails the build.

    python3 tools/fonts/build_name_style_fonts.py              build, verify sources against the lock
    python3 tools/fonts/build_name_style_fonts.py --update-lock build and record source hashes
    python3 tools/fonts/build_name_style_fonts.py --prune      also delete outputs of fonts no longer listed
    python3 tools/fonts/build_name_style_fonts.py --verify     offline: the committed files are the listed fonts and
                                                               each one's cmap covers Turkish
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
import tempfile
import urllib.parse
import urllib.request
from pathlib import Path

from fontTools.subset import Options as SubsetOptions
from fontTools.subset import Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

REPO_ROOT = Path(__file__).resolve().parents[2]
PACKAGE_ROOT = REPO_ROOT / "packages" / "fonts"
LIST_PATH = PACKAGE_ROOT / "name-styles.json"
FILES_DIR = PACKAGE_ROOT / "files" / "NameStyle"
CSS_DIR = PACKAGE_ROOT / "css" / "name-styles"
LICENSE_DIR = PACKAGE_ROOT / "licenses" / "name-styles"
NOTICE_PATH = PACKAGE_ROOT / "NOTICE-NAME-STYLES.md"
LOCK_PATH = Path(__file__).resolve().parent / "name_style_fonts.lock.json"
BASE_FACE = PACKAGE_ROOT / "files" / "FluxerSans" / "FluxerSans-Regular.woff2"

SPDX_CSS_HEADER = "/* SPDX-License-Identifier: AGPL-3.0-or-later */"
GENERATED_HEADER = "/* Generated by tools/fonts/build_name_style_fonts.py. Do not edit by hand. */"

TURKISH = "ğüşıöçİĞÜŞÖÇâîû"
WIDTH_SAMPLE = "İĞDIR ŞÜKRÜ ÇÖĞÜŞ"
UNICODES = [
    *range(0x20, 0x7F),
    *range(0xA0, 0x180),
    0x131,
    0x2C6,
    0x2DA,
    0x2DC,
    *range(0x2010, 0x2028),
    *range(0x2030, 0x203B),
    0x20AC,
    0x20BA,
    0x2122,
]
RENAMED_NAME_IDS = (1, 3, 4, 6, 16, 17, 18, 21, 22, 25)
SIZE_ADJUST_RANGE = (0.7, 1.35)
MAX_WIDTH_RATIO = 1.3


def css_family(font_id: str) -> str:
    return f"sanalyer Name {font_id}"


def file_stem(font_id: str) -> str:
    return f"SanalyerName-{font_id}"


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "fluxer-fonts/1"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def source_bytes(commit: str, path: str, cache: Path) -> bytes:
    cached = cache / commit / path
    if cached.is_file():
        return cached.read_bytes()
    url = f"https://raw.githubusercontent.com/google/fonts/{commit}/{urllib.parse.quote(path)}"
    data = fetch(url)
    cached.parent.mkdir(parents=True, exist_ok=True)
    cached.write_bytes(data)
    return data


def instance(font: TTFont, axes: dict[str, float]) -> TTFont:
    if "fvar" not in font:
        if axes:
            raise ValueError(f"static font given axes {axes}")
        return font
    location = {axis.axisTag: axis.defaultValue for axis in font["fvar"].axes}
    for tag, value in axes.items():
        if tag not in location:
            raise ValueError(f"unknown axis {tag}")
        location[tag] = value
    return instancer.instantiateVariableFont(font, location, updateFontNames=False)


def rename(font: TTFont, family: str) -> None:
    name = font["name"]
    postscript = family.replace(" ", "")
    for record in list(name.names):
        if record.nameID in RENAMED_NAME_IDS:
            name.removeNames(nameID=record.nameID)
    name.setName(family, 1, 3, 1, 0x409)
    name.setName("Regular", 2, 3, 1, 0x409)
    name.setName(f"{family};name-style", 3, 3, 1, 0x409)
    name.setName(family, 4, 3, 1, 0x409)
    name.setName(postscript, 6, 3, 1, 0x409)


def subset(font: TTFont) -> None:
    options = SubsetOptions()
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.hinting = False
    options.desubroutinize = True
    options.notdef_outline = True
    subsetter = Subsetter(options=options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)


def cap_height(font: TTFont) -> float:
    os2 = font["OS/2"]
    value = getattr(os2, "sCapHeight", 0) or 0
    if value <= 0:
        glyph_set = font.getGlyphSet()
        glyph = font.getBestCmap()[ord("H")]
        from fontTools.pens.boundsPen import BoundsPen

        pen = BoundsPen(glyph_set)
        glyph_set[glyph].draw(pen)
        value = pen.bounds[3] if pen.bounds else font["head"].unitsPerEm * 0.7
    return value / font["head"].unitsPerEm


def line_metrics(font: TTFont) -> tuple[float, float]:
    upm = font["head"].unitsPerEm
    os2 = font["OS/2"]
    if os2.fsSelection & (1 << 7):
        return os2.sTypoAscender / upm, -os2.sTypoDescender / upm
    hhea = font["hhea"]
    return hhea.ascent / upm, -hhea.descent / upm


def sample_width(font: TTFont) -> float:
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    fallback = font["head"].unitsPerEm * 0.6
    total = sum(hmtx[cmap[ord(ch)]][0] if ord(ch) in cmap else fallback for ch in WIDTH_SAMPLE)
    return total / font["head"].unitsPerEm


def size_adjust(font: TTFont, base: TTFont) -> float:
    adjust = cap_height(base) / cap_height(font)
    adjust = min(max(adjust, SIZE_ADJUST_RANGE[0]), SIZE_ADJUST_RANGE[1])
    width_ratio = sample_width(font) * adjust / sample_width(base)
    if width_ratio > MAX_WIDTH_RATIO:
        adjust *= MAX_WIDTH_RATIO / width_ratio
    return round(max(adjust, 0.55), 3)


def stylesheet(font_id: str, adjust: float, base: TTFont) -> str:
    ascent, descent = line_metrics(base)
    pct = lambda value: f"{round(value * 100, 2)}%"  # noqa: E731
    return "\n".join(
        [
            SPDX_CSS_HEADER,
            GENERATED_HEADER,
            "",
            "@font-face {",
            f"\tfont-family: '{css_family(font_id)}';",
            f"\tsrc: url('../../files/NameStyle/{file_stem(font_id)}.woff2') format('woff2');",
            "\tfont-weight: 100 900;",
            "\tfont-style: normal;",
            "\tfont-display: swap;",
            f"\tsize-adjust: {pct(adjust)};",
            f"\tascent-override: {pct(ascent / adjust)};",
            f"\tdescent-override: {pct(descent / adjust)};",
            "\tline-gap-override: 0%;",
            "}",
            "",
        ]
    )


def reserved_names(license_text: str) -> list[str]:
    names = []
    for line in license_text.splitlines():
        if "Reserved Font Name" in line and "refers to" not in line:
            names.append(line.strip())
    return names


def verify() -> int:
    config = json.loads(LIST_PATH.read_text(encoding="utf-8"))
    expected = {f"{file_stem(entry['id'])}.woff2" for entry in config["fonts"]}
    present = {path.name for path in FILES_DIR.glob("*.woff2")}
    failures = [f"{name}: listed in name-styles.json but not committed" for name in sorted(expected - present)]
    failures += [f"{name}: committed but not listed in name-styles.json" for name in sorted(present - expected)]
    for name in sorted(expected & present):
        cmap = TTFont(FILES_DIR / name).getBestCmap()
        missing = "".join(ch for ch in TURKISH if ord(ch) not in cmap)
        if missing:
            failures.append(f"{name}: missing Turkish glyphs {missing}")
    if failures:
        print(f"FAIL ({len(failures)} problem(s)):", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        return 1
    print(f"{len(expected)} name style fonts, Turkish OK")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--update-lock", action="store_true")
    parser.add_argument("--prune", action="store_true")
    parser.add_argument("--verify", action="store_true", help="offline: check the committed fonts, build nothing")
    parser.add_argument("--cache", type=Path, default=Path(tempfile.gettempdir()) / "fluxer-name-style-fonts")
    args = parser.parse_args()
    if args.verify:
        return verify()

    config = json.loads(LIST_PATH.read_text(encoding="utf-8"))
    commit = config["source"]["commit"]
    lock = json.loads(LOCK_PATH.read_text(encoding="utf-8")) if LOCK_PATH.is_file() else {"commit": commit, "sha256": {}}
    if lock.get("commit") != commit and not args.update_lock:
        print(f"lock is for {lock.get('commit')}, list pins {commit}; run with --update-lock", file=sys.stderr)
        return 1
    hashes: dict[str, str] = {} if args.update_lock else dict(lock["sha256"])

    base = TTFont(io.BytesIO(BASE_FACE.read_bytes()))
    for directory in (FILES_DIR, CSS_DIR, LICENSE_DIR):
        directory.mkdir(parents=True, exist_ok=True)

    notice = [
        "# Name style font licences",
        "",
        f"The WOFF2 files in `files/NameStyle/` are Modified Versions of fonts from google/fonts at commit `{commit}`.",
        "Each was pinned to one instance, subset to Latin and Latin Extended-A, stripped of hinting and renamed to",
        "`sanalyer Name <id>`, so no Modified Version presents a Reserved Font Name (SIL OFL 1.1 clause 3). The copyright,",
        "licence, designer and vendor records are unchanged. Every font is licensed under the SIL Open Font License,",
        "Version 1.1; its licence text is in `licenses/name-styles/`.",
        "",
        "| id | Original font | Source | Reserved Font Name |",
        "| --- | --- | --- | --- |",
    ]
    report = []
    seen_ids = set()
    for entry in config["fonts"]:
        font_id, path = entry["id"], entry["path"]
        if font_id in seen_ids:
            raise SystemExit(f"duplicate id {font_id}")
        seen_ids.add(font_id)
        directory = path.rsplit("/", 1)[0]
        for source in (path, f"{directory}/OFL.txt"):
            data = source_bytes(commit, source, args.cache)
            digest = hashlib.sha256(data).hexdigest()
            if args.update_lock:
                hashes[source] = digest
            elif hashes.get(source) != digest:
                raise SystemExit(f"{source}: sha256 {digest} does not match the lock")
        license_text = source_bytes(commit, f"{directory}/OFL.txt", args.cache).decode("utf-8")
        if "SIL OPEN FONT LICENSE" not in license_text.upper():
            raise SystemExit(f"{font_id}: licence is not the SIL OFL")

        font = TTFont(io.BytesIO(source_bytes(commit, path, args.cache)))
        font = instance(font, entry.get("axes", {}))
        missing = [ch for ch in TURKISH if ord(ch) not in font.getBestCmap()]
        if missing:
            raise SystemExit(f"{font_id}: missing Turkish glyphs {''.join(missing)}")
        adjust = size_adjust(font, base)
        rename(font, css_family(font_id))
        subset(font)
        font.flavor = "woff2"
        out = io.BytesIO()
        font.save(out)
        woff2 = out.getvalue()
        check = TTFont(io.BytesIO(woff2))
        missing = [ch for ch in TURKISH if ord(ch) not in check.getBestCmap()]
        if missing:
            raise SystemExit(f"{font_id}: subset lost Turkish glyphs {''.join(missing)}")

        (FILES_DIR / f"{file_stem(font_id)}.woff2").write_bytes(woff2)
        (CSS_DIR / f"{font_id}.css").write_text(stylesheet(font_id, adjust, base), encoding="utf-8", newline="\n")
        (LICENSE_DIR / f"{font_id}-OFL.txt").write_text(license_text, encoding="utf-8", newline="\n")
        rfn = "; ".join(reserved_names(license_text)) or "none"
        notice.append(f"| {font_id} | {entry['label']} | `{path}` | {rfn} |")
        report.append((font_id, entry["label"], len(woff2), adjust))

    if args.prune:
        for directory, suffix in ((FILES_DIR, ".woff2"), (CSS_DIR, ".css"), (LICENSE_DIR, "-OFL.txt")):
            for file in directory.iterdir():
                stem = file.name[: -len(suffix)] if file.name.endswith(suffix) else None
                font_id = stem.removeprefix("SanalyerName-") if stem else None
                if font_id is not None and font_id not in seen_ids:
                    file.unlink()

    NOTICE_PATH.write_text("\n".join(notice) + "\n", encoding="utf-8", newline="\n")
    if args.update_lock:
        LOCK_PATH.write_text(
            json.dumps({"commit": commit, "sha256": dict(sorted(hashes.items()))}, indent="\t") + "\n",
            encoding="utf-8",
            newline="\n",
        )
    for font_id, label, size, adjust in report:
        print(f"{font_id:12} {label:16} {size / 1024:6.1f} KB  size-adjust {adjust:.3f}  Turkish OK")
    print(f"{len(report)} fonts, {sum(size for _, _, size, _ in report) / 1024:.1f} KB total")
    return 0


if __name__ == "__main__":
    sys.exit(main())
